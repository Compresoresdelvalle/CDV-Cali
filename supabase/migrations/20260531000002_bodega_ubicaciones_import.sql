-- Import de ubicaciones físicas de BODEGA desde la planilla de productos.
-- Ubicación a nivel producto: stand (1-9) + posición (1-4), o 'stand piso'.
-- Cruce por productos.referencia. Solo afecta productos que existan.
-- ============================================================================

ALTER TABLE public.productos
  ADD COLUMN IF NOT EXISTS en_piso boolean NOT NULL DEFAULT false;

-- La tabla `stands` traía 1-8 (CHECK numero<=8); el layout real de la bodega
-- tiene 9 stands en U. Se amplía el CHECK y se agrega el stand 9 para satisfacer
-- la FK productos.stand → stands. (El metadato lado/orden de los stands
-- existentes corresponde a un layout anterior y se revisará aparte.)
ALTER TABLE public.stands DROP CONSTRAINT IF EXISTS stands_numero_check;
ALTER TABLE public.stands
  ADD CONSTRAINT stands_numero_check CHECK (numero >= 1 AND numero <= 9);

